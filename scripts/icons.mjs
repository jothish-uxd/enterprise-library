// Builds the icon pack from icons/manifest.json and Lucide (lucide-static, ISC).
// Writes src/icons/data.ts (for the Icon component), and dist/icons/: one SVG per
// icon, sprite.svg (<symbol id="icon-NAME">) and LICENSE-lucide.txt.
// Run with `npm run icons` after changing the manifest; `npm run build` runs it too.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const manifest = JSON.parse(readFileSync('icons/manifest.json', 'utf8'));
const src = (name) => readFileSync(`node_modules/lucide-static/icons/${name}.svg`, 'utf8');
const inner = (svg) => svg.replace(/<!--.*?-->/gs, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '')
  .replace(/\s*\n\s*/g, '').replace(/\s{2,}/g, ' ').trim();

const icons = {};
const groups = manifest.groups.map(([group, list]) => ({
  name: group,
  icons: list.map(([name, from, keywords]) => {
    if (icons[name]) throw new Error(`Duplicate icon name: ${name}`);
    icons[name] = inner(src(from));
    return { name, keywords };
  }),
}));

const ts = `// Generated by scripts/icons.mjs from icons/manifest.json. Don't edit by hand.
// Icon shapes from Lucide (https://lucide.dev), ISC licence: see dist/icons/LICENSE-lucide.txt.

export const ICONS = ${JSON.stringify(icons, null, 2)} as const;

export type IconName = keyof typeof ICONS;

export const ICON_GROUPS: { name: string; icons: { name: IconName; keywords: string }[] }[] = ${JSON.stringify(groups, null, 2)};
`;
mkdirSync('src/icons', { recursive: true });
writeFileSync('src/icons/data.ts', ts);

const attrs = 'xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"';
mkdirSync('dist/icons/svg', { recursive: true });
for (const [name, body] of Object.entries(icons)) {
  writeFileSync(`dist/icons/svg/${name}.svg`, `<svg ${attrs} width="24" height="24" aria-hidden="true">${body}</svg>\n`);
}
const symbols = Object.entries(icons).map(([name, body]) => `<symbol id="icon-${name}" viewBox="0 0 24 24">${body}</symbol>`).join('\n');
writeFileSync('dist/icons/sprite.svg', `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">\n${symbols}\n</svg>\n`);
writeFileSync('dist/icons/LICENSE-lucide.txt', readFileSync('node_modules/lucide-static/LICENSE', 'utf8'));
console.log(`Wrote ${Object.keys(icons).length} icons in ${groups.length} groups`);
